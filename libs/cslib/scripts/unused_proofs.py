#!/usr/bin/env python3
"""Builds a proof file for unused-hypothesis verdicts from `UnusedEmit.lean` output.

Each verdict becomes `theorem HypCheckProof.T.h<i> : T' := drop_unused% T i`, where the term
elaborator `drop_unused%` (defined in the file header) takes the library's proof term of `T` and
drops binder `i`; it fails unless that binder is unused and the result has the stated type. The
readable statement is tried first; declarations that fail are switched to the explicit rendering.

Usage: unused_proofs.py STMTS.jsonl OUT.lean IMPORTS(comma) [--rec]
(--rec: recursive `drop_unused%` for transitively unused hypotheses, see HEADER_REC)
"""
import json, os, re, subprocess, sys

LEAN = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'cslean')  # CSLib port: toolchain lean + lake env LEAN_PATH

HEADER = '''/-!
Removable hypotheses that the library's own proof does not use (`scripts/Unused.lean`). Generated
by `scripts/unused_proofs.py`; do not edit by hand.

`drop_unused% T i` is the proof term of `T` with binder `i` dropped. It fails unless binder `i`
does not occur in the proof, nothing in the statement depends on it, and the result has exactly the
stated type `T'` (checked with `isDefEq`); the kernel then checks the declaration as usual.
-/

open Lean Elab Term Meta in
/-- `T'`: the statement of `T` without binder `i`. Used as the statement where the printed one does
not elaborate back. -/
elab "drop_type% " id:ident i:num : term => do
  let ci ← getConstInfo id.getId
  forallTelescope ci.type fun xs body => mkForallFVars (xs.eraseIdxIfInBounds i.getNat) body

open Lean Elab Term Meta in
elab "drop_unused% " id:ident i:num : term <= expectedType => do
  let n := id.getId
  let i := i.getNat
  let ci ← getConstInfo n
  let some v := ci.value? (allowOpaque := true) | throwError "{n} has no proof term"
  forallTelescope ci.type fun xs body => lambdaBoundedTelescope v xs.size fun ys b => do
    unless ys.size == xs.size do throwError "the proof of {n} has fewer binders than its statement"
    let some x := ys[i]? | throwError "{n} has no binder {i}"
    if b.containsFVar x.fvarId! then throwError "binder {i} of {n} is used in its proof"
    let rest := ys.eraseIdxIfInBounds i
    let ty ← mkForallFVars rest (body.replaceFVars xs ys)
    unless ← isDefEq ty expectedType do
      throwError "{n} without binder {i} is{indentExpr ty}\\nnot the stated{indentExpr expectedType}"
    -- universe parameters that only the proof uses (not `T'`) are set to 0
    let pf ← mkLambdaFVars rest b
    let inTy := (collectLevelParams {} ty).params
    let extra := ci.levelParams.filter (!inTy.contains ·)
    return pf.instantiateLevelParams extra (extra.map fun _ => Level.zero)
'''


HEADER_REC = r'''/-!
Removable hypotheses that the library's own proof only passes on to other theorems at hypotheses
that those don't use either (`scripts/UnusedTrans.lean`). Generated by `scripts/unused_proofs.py
--rec`; do not edit by hand.

`drop_unused% T i` builds (once) the helper theorem `HypCheckDrop.T.h<i>`: `T` without binder `i`,
proved by the proof term of `T` in which every call `c … h …` that passes the binder on is replaced
by the call of `HypCheckDrop.c.h<j>` without that argument (built the same way, recursively), and
the binder is then dropped. It fails unless the binder no longer occurs afterwards, nothing in the
statement depends on it, and the result has exactly the stated type `T'` (checked with `isDefEq`).
The kernel checks every helper and every declaration as usual.
-/

open Lean Meta in
/-- `HypCheckDrop.<n>.h<k>`: theorem `n` without binder `k` (see the module docstring). -/
partial def hcDrop (n : Name) (k : Nat) : MetaM Name := do
  let d := (`HypCheckDrop ++ privateToUserName n).str s!"h{k}"
  if (← getEnv).contains d then return d
  let ci ← getConstInfo n
  let .thmInfo _ := ci | throwError "{n} is not a theorem"
  let some v := ci.value? (allowOpaque := true) | throwError "{n} has no proof term"
  let (ty, pf) ← forallTelescope ci.type fun xs body => lambdaBoundedTelescope v xs.size fun ys b => do
    unless ys.size == xs.size do throwError "the proof of {n} has fewer binders than its statement"
    let some x := ys[k]? | throwError "{n} has no binder {k}"
    let body := body.replaceFVars xs ys
    if body.containsFVar x.fvarId! then throwError "the conclusion of {n} depends on binder {k}"
    for y in ys.extract (k+1) ys.size do
      if (← inferType y).containsFVar x.fvarId! then throwError "binder {k} of {n} is dependent"
    let b ← Meta.transform b (pre := fun e => do
      unless e.containsFVar x.fvarId! do return .done e
      let .const c us := e.getAppFn | return .continue
      let args := e.getAppArgs
      let some j := args.findIdx? (· == x) | return .continue
      let .thmInfo _ ← getConstInfo c | return .continue
      let some d' ← (try some <$> hcDrop c j catch _ => pure none) | return .continue
      return .visit (mkAppN (mkConst d' us) (args.eraseIdxIfInBounds j)))
    if b.containsFVar x.fvarId! then throwError "binder {k} of {n} is used in its proof"
    let rest := ys.eraseIdxIfInBounds k
    return (← mkForallFVars rest body, ← mkLambdaFVars rest b)
  addDecl (.thmDecl { name := d, levelParams := ci.levelParams, type := ty, value := pf })
  return d

open Lean Elab Command in
/-- Adds the helper theorems for `drop_unused% T i`. A separate command, since inside a theorem only
declarations below its own name may be added. -/
elab "drop_unused_helpers " id:ident i:num : command =>
  liftTermElabM do discard <| hcDrop id.getId i.getNat

open Lean Elab Term Meta in
/-- `T'`: the statement of `T` without binder `i`. Used as the statement where the printed one does
not elaborate back. -/
elab "drop_type% " id:ident i:num : term => do
  let ci ← getConstInfo id.getId
  forallTelescope ci.type fun xs body => mkForallFVars (xs.eraseIdxIfInBounds i.getNat) body

open Lean Elab Term Meta in
elab "drop_unused% " id:ident i:num : term <= expectedType => do
  let d ← hcDrop id.getId i.getNat
  let ci ← getConstInfo d
  -- universe parameters that only the proof uses (not `T'`) are set to 0
  let inTy := (collectLevelParams {} (← instantiateMVars expectedType)).params
  let us := ci.levelParams.map fun p => if inTy.contains p then mkLevelParam p else Level.zero
  let ty := ci.type.instantiateLevelParams ci.levelParams us
  unless ← isDefEq ty expectedType do
    throwError "{id.getId} without binder {i.getNat} is{indentExpr ty}\nnot the stated{indentExpr expectedType}"
  return mkConst d us
'''

MODES = ['readable', 'explicit', 'computed']

def decl(e, mode):
    pre = f"drop_unused_helpers {e['theorem']} {e['idx']}\n" if '--rec' in sys.argv else ''
    return pre + decl0(e, mode)


def decl0(e, mode):
    d = f"HypCheckProof.{e['theorem']}.h{e['idx']}"
    lv = '.{' + ', '.join(e['lps']) + '}' if e['lps'] else ''
    if mode == 'computed':
        # the printed statement, for reading only (it does not elaborate back)
        shown = '\n'.join('--   ' + l for l in e['readable'].split('\n'))
        return (f"-- `{e['theorem']}` idx {e['idx']}: unused in the library's proof. Statement:\n{shown}\n"
                f"theorem {d}{lv} : drop_type% {e['theorem']} {e['idx']} :=\n"
                f"  no_implicit_lambda% (drop_unused% {e['theorem']} {e['idx']})\n")
    return (f"-- `{e['theorem']}` idx {e['idx']}: unused in the library's proof\n"
            f"theorem {d}{lv} :\n    {e[mode]} :=\n  no_implicit_lambda% (drop_unused% {e['theorem']} {e['idx']})\n")


def build(entries, modes, imports):
    hdr = HEADER_REC if '--rec' in sys.argv else HEADER
    lines = [f'import {m}' for m in imports] + hdr.split('\n')
    ranges = []
    for k, e in enumerate(entries):
        start = len(lines) + 1
        lines += decl(e, modes[k]).split('\n')
        ranges.append((start, len(lines)))
    return '\n'.join(lines) + '\n', ranges


def compile_errors(text, path):
    with open(path, 'w') as f:
        f.write(text)
    r = subprocess.run([LEAN, path], capture_output=True, text=True)
    out = r.stdout + r.stderr
    errs = [(int(m.group(1)), l) for l in out.split('\n')
            if (m := re.match(r'^[^:]+:(\d+):\d+: error', l))]
    return errs, out


def main():
    stmts, out, imports = sys.argv[1], sys.argv[2], sys.argv[3].split(',')
    entries = [json.loads(l) for l in open(stmts) if l.strip()]
    mode = [0] * len(entries)
    dropped = set()
    # Lean reports at most about 100 errors per file, so repeat until the file compiles: each
    # failing declaration moves to the next rendering, and is dropped once `computed` fails too.
    for rnd in range(40):
        live = [k for k in range(len(entries)) if k not in dropped]
        text, ranges = build([entries[k] for k in live], [MODES[mode[k]] for k in live], imports)
        errs, _ = compile_errors(text, out)
        bad = {live[j] for ln, _ in errs for j, (a, b) in enumerate(ranges) if a <= ln <= b}
        other = [l for ln, l in errs if not any(a <= ln <= b for a, b in ranges)]
        print(f'round {rnd}: {len(errs)} errors in {len(bad)} declarations, {len(other)} elsewhere')
        for l in other[:5]: print('  ', l)
        if not errs: break
        for k in bad:
            if mode[k] + 1 < len(MODES): mode[k] += 1
            else: dropped.add(k)
    failed = [entries[k] for k in sorted(dropped)]
    keep = [k for k in range(len(entries)) if k not in dropped]
    entries = [entries[k] for k in keep]; mode = [mode[k] for k in keep]
    import collections
    print(f'{len(entries)} declarations', collections.Counter(MODES[m] for m in mode), f'-> {out}')
    with open(out + '.ok.jsonl', 'w') as f:
        for e, m in zip(entries, mode):
            f.write(json.dumps({'theorem': e['theorem'], 'idx': e['idx'], 'rendering': MODES[m]}) + '\n')


main()
