#!/usr/bin/env python3
"""Write certs/platform/PCert{32,64}_<File>.lean: SwapCheck certificates for the platform rows.

Each file imports one support file (checks/<File>.lean, compiled by swapcheck.sh), swaps
`System.Platform.getNumBits` to return k, and runs `pcert% T i` per row, which proves either
`S` (`pos`) or `¬S` (`neg`) from that row's hand lemma, where `S` is `T'` (`pdrop0%`) or, for a
dependent hypothesis, `∀ indep, Hᵢ` (`pindep0%`). Run from libs/core."""
import json, collections, os

HEADER = r'''import Lean
import {mod}

/-! SwapCheck certificate (generated by `scripts/gen_platform_certs.py`): platform rows supported
by `checks/{mod}.lean`, in the library with `System.Platform.getNumBits` returning {k}. Check with
`scripts/swapcheck.sh certs/platform/{name}.lean`. -/

open Lean Meta Elab Term in
/-- `T` without its non-dependent Prop binder `i`, all universe parameters set to `0`. -/
elab "pdrop0% " T:ident i:num : term => do
  let n ← realizeGlobalConstNoOverloadWithInfo T
  let ci ← getConstInfo n
  let us := ci.levelParams.map fun _ => Level.zero
  forallTelescope (ci.type.instantiateLevelParams ci.levelParams us) fun xs body => do
    let x := xs[i.getNat]!
    unless ← isProp (← inferType x) do throwError "binder {{i.getNat}} of {{n}} is not a Prop"
    for j in [i.getNat+1:xs.size] do
      if (← inferType xs[j]!).containsFVar x.fvarId! then throwError "binder {{i.getNat}} of {{n}} is dependent"
    if body.containsFVar x.fvarId! then throwError "binder {{i.getNat}} of {{n}} is dependent"
    mkForallFVars (xs.eraseIdx! i.getNat) body

open Lean Meta Elab Term in
/-- `∀ indep, Hᵢ` for the dependent Prop binder `i` of `T`, universe parameters set to `0`. -/
elab "pindep0% " T:ident i:num : term => do
  let n ← realizeGlobalConstNoOverloadWithInfo T
  let ci ← getConstInfo n
  let us := ci.levelParams.map fun _ => Level.zero
  forallTelescope (ci.type.instantiateLevelParams ci.levelParams us) fun xs body => do
    let x := xs[i.getNat]!
    unless ← isProp (← inferType x) do throwError "binder {{i.getNat}} of {{n}} is not a Prop"
    let mut dep := #[x]
    for j in [i.getNat+1:xs.size] do
      let t ← inferType xs[j]!
      if dep.any (fun d => t.containsFVar d.fvarId!) then dep := dep.push xs[j]!
    unless dep.size > 1 || body.containsFVar x.fvarId! do
      throwError "binder {{i.getNat}} of {{n}} is not dependent"
    mkForallFVars (xs.filter (fun y => !dep.contains y)) (← inferType x)

axiom PCert.swap : @System.Platform.getNumBits = fun _ => ⟨{k}, {orproof}⟩

theorem PCert.numBits_eq : System.Platform.numBits = {k} := by
  unfold System.Platform.numBits; rw [PCert.swap]

open Lean Meta Elab Term Command in
/-- `pcert% T i`: add `PCert.pos.T.hi : S` or `PCert.neg.T.hi : ¬S`, proved from a hand lemma of
the imported support module named `….T.hi`, `….T.hi_pos` or `….T.hi_neg`. -/
elab "pcert% " T:ident i:num : command => liftTermElabM <| withoutErrToSorry do
  let n ← realizeGlobalConstNoOverloadWithInfo T
  let hi := s!"h{{i.getNat}}"
  let tails := [hi, hi ++ "_pos", hi ++ "_neg"].map fun s => n.components ++ [Name.mkSimple s]
  let env ← getEnv
  let mut cands : Array Name := #[]
  for mod in env.header.moduleNames, data in env.header.moduleData do
    if mod == `{mod} then
      for c in data.constNames do
        let cs := c.components
        if tails.any (fun t => cs.length ≥ t.length && cs.drop (cs.length - t.length) == t) then
          cands := cands.push c
  if cands.isEmpty then throwError "no hand lemma for {{n}} {{hi}}"
  let (S, kind) ← try pure (← elabTermAndSynthesize (← `(pindep0% $T $i)) none, "indep")
    catch _ => pure (← elabTermAndSynthesize (← `(pdrop0% $T $i)) none, "drop")
  let S ← instantiateMVars S
  let numEq := Lean.mkConst ``PCert.numBits_eq
  -- `tryTerm mk goal`: the term `mk` builds, if its type is `goal` (state restored otherwise)
  let tryTerm (mk : TermElabM Expr) (goal : Expr) : TermElabM (Option Expr) := do
    let s ← saveState
    try
      let v ← mk
      if ← isDefEq (← inferType v) goal then
        let v ← instantiateMVars v
        if !v.hasMVar && !v.hasSorry then
          Meta.check v
          return some v
      s.restore; return none
    catch _ => s.restore; return none
  for (sign, goal) in [("pos", S), ("neg", mkNot S)] do
    for L in cands do
      let mk : TermElabM Expr := do
        let Lc ← mkConstWithFreshMVarLevels L
        let Lty ← inferType Lc
        match Lty.iff?, sign with
        | some (A, B), "pos" =>
          -- `L : A ↔ B` with `B` true at `numBits = k` (`numBits = k` or `numBits ≠ k'`)
          let pb ← mkFreshExprMVar B
          let gs ← Tactic.run pb.mvarId! <| Tactic.evalTactic
            (← `(tactic| first | exact PCert.numBits_eq | (rw [PCert.numBits_eq]; decide)))
          unless gs.isEmpty do throwError "B"
          return mkApp4 (Lean.mkConst ``Iff.mpr) A B Lc (← instantiateMVars pb)
        | some (A, B), _ =>
          -- `L : A ↔ B` with `B` false at `numBits = k`: `fun h : A => absurd (L.mp h) _`
          let ne ← mkFreshExprMVar (mkNot B)
          let gs ← Tactic.run ne.mvarId! <| Tactic.evalTactic
            (← `(tactic| (rw [PCert.numBits_eq]; decide)))
          unless gs.isEmpty do throwError "ne"
          return .lam `h A (mkApp4 (Lean.mkConst ``absurd [.zero]) B (Lean.mkConst ``False)
            (mkApp4 (Lean.mkConst ``Iff.mp) A B Lc (.bvar 0)) (← instantiateMVars ne)) .default
        | none, _ => return mkApp Lc numEq
      let some val ← tryTerm mk goal | continue
      let name := (Name.mkSimple "PCert" |>.str sign) ++ n |>.str hi
      addDecl <| .thmDecl {{ name, levelParams := [], type := goal, value := val }}
      logInfo m!"{{name}} ({{kind}}) via {{L}}"
      return
  throwError "no certificate for {{n}} {{hi}} among {{cands}}"

'''

rows = [r for r in map(json.loads, open('results/init_all.jsonl')) if r.get('independence') == 'platform']
byfile = collections.defaultdict(list)
for r in rows:
    f = os.path.basename(r['independent_support'].split()[0]).removesuffix('.lean')
    f = {'UIntBitwiseIndep': 'UIntBitwiseNamed'}.get(f, f)  # named copies of its examples
    byfile[f].append(r)
os.makedirs('certs/platform', exist_ok=True)
for f, rs in sorted(byfile.items()):
    for k, orproof in ((32, 'Or.inl rfl'), (64, 'Or.inr rfl')):
        name = f'PCert{k}_{f}'
        with open(f'certs/platform/{name}.lean', 'w') as out:
            out.write(HEADER.format(mod=f, k=k, orproof=orproof, name=name))
            for r in rs:
                t = '.'.join('«%s»' % c if not c.replace('_', 'a').replace("'", 'a').isalnum() else c
                             for c in r['theorem'].split('.'))
                out.write(f"pcert% {t} {r['idx']}\n")
    print(f, len(rs))
