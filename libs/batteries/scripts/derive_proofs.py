#!/usr/bin/env python3
"""Builds a proof file for instance hypotheses that type class resolution derives from the other
binders (`scripts/InstDerivable.lean`), reusing `unused_proofs.py`.

Each verdict becomes `theorem HypCheckProof.T.h<i> : T' := no_implicit_lambda% (derive_inst% T i)`:
`T` applied to the instance that `synthInstance` finds for binder `i` from the remaining binders.

Usage: derive_proofs.py STMTS.jsonl OUT.lean IMPORTS(comma)   (STMTS from UnusedEmit.lean)
"""
import os, sys, importlib.util

HEADER = '''/-!
Removable instance hypotheses that type class resolution derives from the theorem's other binders
(`scripts/InstDerivable.lean`). Generated by `scripts/derive_proofs.py`; do not edit by hand.

`derive_inst% T i` is `fun rest => T … inst …`, where `inst` is the instance that `synthInstance`
finds for binder `i` in the context of the remaining binders (so binder `i` itself is not
available). It fails unless the statement doesn't depend on binder `i` and `T` without binder `i`
is exactly the stated type (`isDefEq`); the kernel then checks the declaration as usual.
-/

open Lean Elab Term Meta in
/-- `T'`: the statement of `T` without binder `i`. -/
elab "drop_type% " id:ident i:num : term => do
  let ci ← getConstInfo id.getId
  forallTelescope ci.type fun xs body => mkForallFVars (xs.eraseIdxIfInBounds i.getNat) body

open Lean Elab Term Meta in
elab "derive_inst% " id:ident i:num : term <= expectedType => do
  let n := id.getId
  let i := i.getNat
  let ci ← getConstInfo n
  let us ← ci.levelParams.mapM fun _ => mkFreshLevelMVar
  let tyT := ci.type.instantiateLevelParams ci.levelParams us
  forallTelescope tyT fun xs body => do
    let some x := xs[i]? | throwError "{n} has no binder {i}"
    if body.containsFVar x.fvarId! then throwError "the statement of {n} depends on binder {i}"
    let rest := xs.eraseIdxIfInBounds i
    for y in rest do
      if (← inferType y).containsFVar x.fvarId! then throwError "binder {y} depends on binder {i}"
    let hx ← inferType x
    let ty ← mkForallFVars rest body
    unless ← isDefEq ty expectedType do
      throwError "{n} without binder {i} is{indentExpr ty}\\nnot the stated{indentExpr expectedType}"
    forallTelescope (← instantiateMVars ty) fun ys _ => do
      let inst ← synthInstance (hx.replaceFVars rest ys)
      let args := (List.range xs.size).toArray.map fun j =>
        if j == i then inst else ys[if j < i then j else j - 1]!
      instantiateMVars (← mkLambdaFVars ys (mkAppN (mkConst n us) args))
'''

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('up', os.path.join(here, 'unused_proofs.py'))
src = open(os.path.join(here, 'unused_proofs.py')).read().replace('\nmain()\n', '\n')
up = importlib.util.module_from_spec(spec)
exec(compile(src, 'unused_proofs.py', 'exec'), up.__dict__)
up.HEADER = HEADER
_decl0 = up.decl0
up.decl0 = lambda e, mode: (_decl0(e, mode).replace('drop_unused%', 'derive_inst%')
                            .replace("unused in the library's proof", 'derivable by instance resolution'))
up.main()
