"""Removable by transitivity: open rows (B, j), non-dependent, whose hypothesis the library proof of B passes only
to hypotheses (A, i) that are already non-dependent removable with a stored proof of A'. Replacing each such call
`A … h_j …` in B's proof by A's proof of A' (binder i dropped) proves B'. Measured on the decided Std/Init rows:
2,549 removable verdicts that agents proved by hand would have followed this way.

Usage (from the workspace root): python3 scripts/rem_trans.py K [--dry]
  -> checks/RemTrans<K>g<n>Hand.lean (one file per source proof file, since two hand files can't be imported
     together: each defines the header's elaborators), checked by check_hand.py with axioms, merged as
     found_by "rem-transitive" via merge_hand.py (run dir runs/remtrans). Public rows only.
A's proof is located by the row's `proof_file`/`proof_decl` (merge_hand.py records them from check_hand.py's
declaration map), by `proof`/`proofs_file` for HypCheck runs, or by re-reading the map of the hand file named in
`tactic`. Source files are copied to runs/remtrans/mods/RT_<path>.lean and compiled there as modules (imported via
HC_EXTRA_PATH); keep that directory: recompiling a RemTrans file needs it."""
import json, os, re, subprocess, sys, glob, collections, shutil
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hcconf
import results_io as io

K = sys.argv[1]
DRY = '--dry' in sys.argv
MODS = os.path.abspath('runs/remtrans/mods')
CAP = hcconf.cap()  # before ENV, so ENV carries the detected HC_CAP
ENV = dict(os.environ, HC_EXTRA_PATH=MODS + (':' + os.environ['HC_EXTRA_PATH'] if os.environ.get('HC_EXTRA_PATH') else ''))

HEADER = r'''
/-! Removable verdicts by transitivity. Generated by `scripts/rem_trans.py`; do not edit by hand.
`hc_rt_drop% B j` is B' (B without its non-dependent Prop binder j). `hc_rem_trans% B j (A i P)*` is B's library
proof with every call `A … h_j …` replaced by `P …` (P : A', binder i dropped); it fails unless h_j no longer occurs
and the result has the stated type. The kernel checks each declaration as usual. -/
open Lean Elab Term Meta

def hcRTDropType (n : Name) (i : Nat) (us : List Level) : MetaM Expr := do
  let ci ← getConstInfo n
  forallTelescope (ci.type.instantiateLevelParams ci.levelParams us) fun xs body => do
    let some x := xs[i]? | throwError "{n} has no binder {i}"
    if body.containsFVar x.fvarId! then throwError "{n}: the statement depends on binder {i}"
    for y in xs.extract (i+1) xs.size do
      if (← inferType y).containsFVar x.fvarId! then throwError "{n}: binder {i} is dependent"
    mkForallFVars (xs.eraseIdxIfInBounds i) body

elab "hc_rt_drop% " b:ident j:num : term => do
  let ci ← getConstInfo b.getId
  hcRTDropType b.getId j.getNat (← ci.levelParams.mapM fun _ => mkFreshLevelMVar)

syntax hcRTArg := "(" ident num ident ")"

elab "hc_rem_trans% " b:ident j:num rs:hcRTArg* : term <= expected => do
  let B := b.getId; let j := j.getNat
  let ci ← getConstInfo B
  let some v := ci.value? (allowOpaque := true) | throwError "{B} has no proof term"
  let us ← ci.levelParams.mapM fun _ => mkFreshLevelMVar
  let ty := ci.type.instantiateLevelParams ci.levelParams us
  let v := v.instantiateLevelParams ci.levelParams us
  forallTelescope ty fun xs body => lambdaBoundedTelescope v xs.size fun ys pb => do
    unless ys.size == xs.size do throwError "{B}: fewer lambdas than binders"
    let some y := ys[j]? | throwError "{B} has no binder {j}"
    let mut pb' := pb
    for r in rs do
      let A := r.raw[1].getId; let i := r.raw[2].toNat; let P := r.raw[3].getId
      let some (.const _ ls) := pb.find? (·.isConstOf A) | throwError "{A} does not occur in the proof of {B}"
      let tA ← hcRTDropType A i ls
      let p ← mkConstWithFreshMVarLevels P
      unless ← isDefEq (← inferType p) tA do throwError "{P} does not prove {A} without binder {i}"
      let p ← instantiateMVars p
      pb' ← Meta.transform pb' (post := fun e => do
        if e.isAppOf A then
          let args := e.getAppArgs
          if hk : i < args.size then
            if args[i] == y then
              let .const _ ls' := e.getAppFn | return .continue
              unless ← isDefEq (mkConst A ls') (mkConst A ls) do throwError "{A} is used at several universe levels"
              return .done (mkAppN p (args.eraseIdxIfInBounds i))
        return .continue)
    if pb'.containsFVar y.fvarId! then throwError "binder {j} of {B} is still used"
    let rest := ys.eraseIdxIfInBounds j
    let tyB ← mkForallFVars rest (body.replaceFVars xs ys)
    unless ← isDefEq tyB expected do
      throwError "{B} without binder {j} is{indentExpr tyB}\nnot the stated type{indentExpr expected}"
    instantiateMVars (← mkLambdaFVars rest pb')
'''


def load():
    rows = {(r['theorem'], r['idx']): r for r in io.load('public')}
    return rows


_maps = {}
def hand_map(path):
    if path not in _maps:
        p = path + '.map.jsonl'
        _maps[path] = {(m['theorem'], m['idx']): m['decl'] for m in map(json.loads, open(p))
                       if m['status'] == 'removable'} if os.path.exists(p) else {}
    return _maps[path]


_parts = {}
def locate(r):
    """(file, declaration) of a stored proof of A', or None."""
    if r.get('proof_file') and r.get('proof_decl'):
        return r['proof_file'], r['proof_decl']
    if r.get('proof') and r.get('proofs_file') and r.get('proof_ok'):
        d = r['proofs_file']
        if d not in _parts:
            _parts[d] = {}
            for f in sorted(glob.glob(d + '/part_*.lean')):
                for m in re.finditer(r'^theorem (\S+)', open(f).read(), re.M):
                    _parts[d][re.sub(r'\.\{[^}]*\}$', '', m.group(1))] = f
        if r['proof'] in _parts[d]:
            return _parts[d][r['proof']], r['proof']
    m = re.search(r'\((checks/\S+\.lean)\)', r.get('tactic') or '')
    if m:
        dcl = hand_map(m.group(1)).get((r['theorem'], r['idx']))
        if dcl: return m.group(1), dcl
        # generated files (struct_proofs.sh, HypCheck) name the proof HypCheckProof.<T>.h<i>
        dcl = f"HypCheckProof.{r['theorem']}.h{r['idx']}"
        if os.path.exists(m.group(1)) and re.search(rf'^theorem {re.escape(dcl)}(\.\{{|\s)', open(m.group(1)).read(), re.M):
            return m.group(1), dcl
    return None


def modname(path):
    return 'RT_' + re.sub(r'\W', '_', path.removesuffix('.lean'))


def compile_mod(path):
    os.makedirs(MODS, exist_ok=True)
    m = modname(path); src = f'{MODS}/{m}.lean'; ol = f'{MODS}/{m}.olean'
    if os.path.exists(ol) and os.path.getmtime(ol) >= os.path.getmtime(path):
        return m, True
    shutil.copy(path, src)
    r = subprocess.run(CAP + [hcconf.LEAN, '-R', MODS, '-o', ol, src], capture_output=True, text=True, env=ENV)
    ok = r.returncode == 0 and os.path.exists(ol)
    if not ok:
        print(f'  module {m} failed to compile:', (r.stdout + r.stderr)[:400])
    return m, ok


def run_file(path, mod, cmds):
    """Write the file, drop failing declarations in rounds; returns kept indices."""
    live = list(range(len(cmds)))
    for rnd in range(10):
        lines = [f'import {mod}'] + HEADER.split('\n'); ranges = []
        for k in live:
            s = len(lines) + 1; lines += ['', *cmds[k].split('\n')]; ranges.append((s, len(lines)))
        open(path, 'w').write('\n'.join(lines) + '\n')
        r = subprocess.run(CAP + [hcconf.LEAN, path], capture_output=True, text=True, env=ENV)
        errs = [int(m.group(1)) for l in (r.stdout + r.stderr).split('\n') if (m := re.match(r'^[^:]+:(\d+):\d+: error', l))]
        if errs and rnd == 0:
            print('  first errors:', ' | '.join(l[l.find('error'):][:300] for l in (r.stdout + r.stderr).split('\n') if ': error' in l)[:900])
        bad = {live[j] for ln in errs for j, (a, b) in enumerate(ranges) if a <= ln <= b}
        other = [ln for ln in errs if not any(a <= ln <= b for a, b in ranges)]
        if not errs: return live
        if other:
            print(f'  {path}: errors outside declarations (lines {other[:5]}); giving up on this file')
            return []
        live = [k for k in live if k not in bad]
    return live


rows = load()
cands = collections.defaultdict(list)  # source file -> [(B, j, [(A, i, decl)])]
stats = collections.Counter()
for e in map(json.loads, open('runs/struct/edges_all.jsonl')):
    B = (e['B'], e['j']); rb = rows.get(B)
    if not rb or rb['status'] != 'unresolved' or rb.get('dependent'): continue
    ts = sorted({tuple(t) for t in e['targets']} - {B})
    if not ts or not all(t in rows and rows[t]['status'] == 'removable' and not rows[t].get('dependent') for t in ts):
        continue
    locs = [locate(rows[t]) for t in ts]
    if None in locs: stats['target proof not located'] += 1; continue
    files = {f for f, _ in locs}
    if len(files) > 1: stats['targets in several files'] += 1; continue
    cands[files.pop()].append((B, [(t[0], t[1], d) for t, (_, d) in zip(ts, locs)]))
    stats['candidates'] += 1
print(f'round {K}:', dict(stats))
if DRY or not stats['candidates']:
    sys.exit(0)
os.makedirs('runs/remtrans', exist_ok=True)
merged = collections.Counter()
for g, (src, cs) in enumerate(sorted(cands.items())):
    mod, ok = compile_mod(src)
    if not ok: continue
    C = f'RemTrans{K}g{g}'; path = f'checks/{C}Hand.lean'
    cmds = []
    for n, ((b, j), ts) in enumerate(cs):
        via = ', '.join(f'`{a}` idx {i}' for a, i, _ in ts)
        cmds.append(f"-- `{b}` idx {j}: removable, its hypothesis only feeds removable {via}\n"
                    f"theorem rt{K}g{g}_{n} : hc_rt_drop% {b} {j} :=\n  no_implicit_lambda% (hc_rem_trans% {b} {j} "
                    + ' '.join(f'({a} {i} {d})' for a, i, d in ts) + ')')
    keep = run_file(path, mod, cmds)
    with open(f'runs/remtrans/{C}_verdicts.jsonl', 'w') as f:
        for k in keep:
            (b, j), ts = cs[k]
            f.write(json.dumps(dict(rows[(b, j)], status='removable', derivable=False,
                                    note='removable by transitivity from ' + ', '.join(f'{a} idx {i}' for a, i, _ in ts)),
                               ensure_ascii=False) + '\n')
    if not keep:
        print(f'  {C}: 0 of {len(cs)} kept'); continue
    out = subprocess.run(CAP + ['python3', 'scripts/check_hand.py', path, f'runs/remtrans/{C}_verdicts.jsonl'],
                         capture_output=True, text=True, env=dict(ENV, HANDCHECK_AXIOMS='1')).stdout
    summ = [l for l in out.split('\n') if l.startswith(('lean errors', 'axioms:'))]
    print(f'  {C}: {len(keep)} of {len(cs)} kept; ' + ' | '.join(summ))
    if (any('lean errors: 0;' in l and 'not covered: 0' in l for l in summ)
            and any(re.match(r'axioms: \d+ standard, 0 other, 0 missing', l) for l in summ)):
        r = subprocess.run(['python3', 'scripts/merge_hand.py', 'runs/remtrans', C, 'rem-transitive'],
                           capture_output=True, text=True, env=ENV)
        m = re.search(r"'removable': (\d+)", r.stdout.split('\n')[0]) if r.returncode == 0 else None
        if m: merged['removable'] += int(m.group(1))
        else: print(f'  {C}: merge FAILED', (r.stdout + r.stderr)[-400:])
    else:
        print(f'  {C}: check failed, not merged')
print(f'rem-trans {K}: merged', dict(merged))
