#!/usr/bin/env python3
"""Stored proofs for the proof-repair verdicts of HypCheck v12 (`--level search|thorough`, rows with
`status: removable, tactic: repair`).

Each verdict becomes `theorem HypCheckProof.T.h<i> : hc_drop_type% T i := hc_repair% T i`. The term elaborator
`hc_repair%` (defined in the file header) reruns the repair: the library proof of `T` applied to the binders, every
use of binder `i` rebuilt (holes closed by cheap tactics in the local context there, internal auxiliary theorems
inlined, library theorems unfolded up to depth 3, eliminators with `h` as an extra argument rebuilt without it);
it fails unless the binder no longer occurs. The repair code is the module `HCRepair` (`scripts/HCRepair.lean`, compiled
by `scripts/build_tools.sh` to `tools/hcrepair`, on the search path via `scripts/hclean`), the same code the tool
uses; `hc_repair%` runs it with the thorough budgets and no wall-clock limit, so what the tool found within its
limits is found again. Declarations that fail are dropped (the file is recompiled until it compiles); the kernel checks the
rest as usual.

Usage (from the workspace root): python3 scripts/repair_proofs.py K TOOLOUT.jsonl [TOOLOUT2.jsonl ...]
  -> checks/Repair<K>Hand.lean (+ .ok.jsonl), runs/repair/Repair<K>_verdicts.jsonl, then check_hand.py with axioms
     and, if clean (0 errors, 0 not covered, standard axioms), merge_hand.py runs/repair Repair<K> proof-repair.
  Env: DRY=1 stops before merging; MEM (default 4G) caps each Lean call.
"""
import json, os, re, subprocess, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hcconf

CAP = ['systemd-run', '--user', '--scope', '--quiet', f'--slice={hcconf.SLICE}', '-p',
       f"MemoryMax={os.environ.get('MEM', '4G')}", '-p', 'MemorySwapMax=0']


def header():
    return ('import HCRepair\n' + hcconf.IMPORTS + '''

/-!
Removable hypotheses by proof repair (HypCheck v12, `--level search|thorough`). Generated by
`scripts/repair_proofs.py`; do not edit by hand. `hc_repair% T i` (module `HCRepair`) rebuilds the library proof of
`T` without binder `i`; `hc_drop_type% T i` is `T'`. The kernel checks every declaration as usual.
-/

''')


def decl(e):
    t, i = e['theorem'], e['idx']
    return (f"-- `{t}` idx {i}: removable by proof repair\n"
            f"set_option maxHeartbeats 0 in\n"
            f"theorem HypCheckProof.{t}.h{i} : hc_drop_type% {t} {i} :=\n  no_implicit_lambda% (hc_repair% {t} {i})\n")


def build(entries):
    lines = header().split('\n')
    ranges = []
    for e in entries:
        start = len(lines) + 1
        lines += decl(e).split('\n')
        ranges.append((start, len(lines)))
    return '\n'.join(lines) + '\n', ranges


def compile_errors(text, path):
    with open(path, 'w') as f:
        f.write(text)
    r = subprocess.run(CAP + [hcconf.LEAN, path], capture_output=True, text=True)
    out = r.stdout + r.stderr
    errs = [(int(m.group(1)), l) for l in out.split('\n') if (m := re.match(r'^[^:]+:(\d+):\d+: error', l))]
    return errs, out


def main():
    K, outs = sys.argv[1], sys.argv[2:]
    rows = {}
    for f in outs:
        for l in open(f):
            r = json.loads(l)
            if r.get('status') == 'removable' and r.get('tactic') == 'repair':
                rows[(r['theorem'], r['idx'])] = r
    entries = list(rows.values())
    print(f'{len(entries)} repair verdicts')
    if not entries:
        return
    os.makedirs('runs/repair', exist_ok=True)
    out = f'checks/Repair{K}Hand.lean'
    live = list(range(len(entries)))
    for rnd in range(40):
        text, ranges = build([entries[k] for k in live])
        errs, log = compile_errors(text, out)
        bad = {live[j] for ln, _ in errs for j, (a, b) in enumerate(ranges) if a <= ln <= b}
        other = [l for ln, l in errs if not any(a <= ln <= b for a, b in ranges)]
        print(f'round {rnd}: {len(errs)} errors in {len(bad)} declarations, {len(other)} elsewhere')
        for l in other[:5]:
            print('  ', l)
        if other:
            sys.exit('errors outside the declarations (header): fix before merging')
        if not errs:
            break
        live = [k for k in live if k not in bad]
    kept = [entries[k] for k in live]
    with open(out + '.ok.jsonl', 'w') as f:
        for e in kept:
            f.write(json.dumps({'theorem': e['theorem'], 'idx': e['idx']}) + '\n')
    with open(f'runs/repair/Repair{K}_verdicts.jsonl', 'w') as f:
        for e in kept:
            f.write(json.dumps(dict(e, status='removable', derivable=False,
                                    note='proof repair of the library proof (hc_repair%)'), ensure_ascii=False) + '\n')
    print(f'{len(kept)} of {len(entries)} declarations compile -> {out}')
    if not kept:
        sys.exit('nothing to check or merge')
    env = dict(os.environ, HANDCHECK_AXIOMS='1')
    r = subprocess.run(CAP + ['python3', 'scripts/check_hand.py', out, f'runs/repair/Repair{K}_verdicts.jsonl'],
                       capture_output=True, text=True, env=env)
    summary = [l for l in (r.stdout + r.stderr).split('\n') if re.search(r'lean errors|NOT COVERED|^axioms:|AXIOMS', l)]
    print('\n'.join(summary))
    clean = any(re.search(r'lean errors: 0;.*not covered: 0', l) for l in summary) and \
        any(re.search(r'axioms: \d+ standard, 0 other, 0 missing', l) for l in summary)
    if not clean:
        sys.exit('check_hand not clean: not merged')
    if os.environ.get('DRY'):
        print('DRY=1: not merged')
        return
    subprocess.run(['python3', 'scripts/merge_hand.py', 'runs/repair', f'Repair{K}', 'proof-repair'], check=True)


if __name__ == '__main__':
    main()
